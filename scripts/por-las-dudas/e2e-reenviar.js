const { chromium } = require('/opt/node22/lib/node_modules/playwright');
const B = 'http://localhost:8799';
(async () => {
  const nav = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium-1194/chrome-linux/chrome', args: ['--no-sandbox'] });
  const ctx = await nav.newContext({ viewport: { width: 390, height: 844 } });
  const pag = await ctx.newPage(); const err = []; pag.on('pageerror', (e) => err.push(e.message));
  let acepta = true, msgs = []; pag.on('dialog', (d) => { msgs.push(d.message()); acepta ? d.accept() : d.dismiss(); });
  await pag.goto(B + '/por-las-dudas');
  await pag.waitForFunction(() => document.getElementById('hoy').textContent.includes('señales'));
  console.log('senal:', (await pag.textContent('#hoy')).match(/Sin señal hace [^A]*?(minuto|minutos|horas|hora)/)?.[0]);
  await pag.fill('#rNombre', 'mama'); await pag.fill('#rCorreo', 'marianaflombaum@gmail.com'); await pag.click('#rAgregar');
  await pag.waitForFunction(() => document.getElementById('invitacion').textContent.includes('mama'));
  const viejo = await pag.inputValue('#invitacion input');
  console.log('antes de aceptar, boton:', await pag.textContent('#referentes .fila button'));
  const ref = await ctx.newPage(); await ref.goto(viejo);
  await ref.waitForSelector('text=Aceptar ser referente'); await ref.click('text=Aceptar ser referente'); await ref.waitForSelector('text=No lo encuentro');
  await pag.reload(); await pag.waitForFunction(() => document.getElementById('referentes').textContent.includes('aceptó'));
  console.log('despues de aceptar, botones:', (await pag.$$eval('#referentes button', (b) => b.map((x) => x.textContent))).join(' | '));
  const n0 = (await (await fetch(B + '/__correos')).json()).length;
  await pag.click('text=Mandar enlace de nuevo'); await pag.waitForFunction(() => document.getElementById('invitacion').textContent.includes('mama'));
  const nuevo = await pag.inputValue('#invitacion input');
  const n1 = (await (await fetch(B + '/__correos')).json()).length;
  console.log('mandar de nuevo -> mails nuevos:', n1 - n0, '| diálogos:', msgs.length, '| mismo enlace:', nuevo === viejo, '| aviso:', JSON.stringify(await pag.textContent('#aviso')));
  const e = async (u) => (await fetch(B + '/api/referente/estado', { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ t: new URL(u).searchParams.get('t') }) }));
  console.log('enlace del primer mail:', (await e(viejo)).status, '| enlace del reenvío:', (await e(nuevo)).status);
  console.log('errores:', err.length ? err : 'ninguno');
  await nav.close();
})().catch((e) => { console.log('FALLO', e.message); process.exit(1); });
