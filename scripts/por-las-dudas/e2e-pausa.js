const { chromium } = require('/opt/node22/lib/node_modules/playwright');
const B = 'http://localhost:8799';
(async () => {
  const nav = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium-1194/chrome-linux/chrome', args: ['--no-sandbox'] });
  const ctx = await nav.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, locale: 'es-AR' });
  const pag = await ctx.newPage();
  const vista = async (h) => { await pag.evaluate((x) => { location.hash = x; }, h); await pag.waitForSelector('#' + ({ '': 'vInicio', cautela: 'vCautela', guardian: 'vGuardian', 'tus-referentes': 'vReferentes' })[h], { state: 'visible' }); };
  const errores = [];
  pag.on('pageerror', (e) => errores.push('pageerror: ' + e.message));
  pag.on('console', (m) => { if (m.type() === 'error') errores.push('console: ' + m.text()); });
  const dialogos = [];
  pag.on('dialog', (d) => { dialogos.push(d.message()); d.accept(); });
  await pag.goto(B + '/por-las-dudas');
  await pag.waitForFunction(() => document.getElementById('hoy').textContent.includes('señales'));
  await vista('cautela');
  const estado = () => pag.textContent('#estadoModo');
  const pausa = () => pag.textContent('#pausa');
  console.log('estado inicial:', await estado(), '| boton:', await pag.textContent('#cEncender'), '|', await pausa());
  await pag.click('button[data-h="12"]');
  await pag.waitForFunction(() => document.getElementById('aviso').textContent.includes('12 horas'));
  console.log('tras 12 h:', await estado(), '|', await pausa(), '| aviso:', await pag.textContent('#aviso'));
  await pag.fill('#pHoras', '36');
  await pag.click('#pOtro');
  await pag.waitForFunction(() => document.getElementById('aviso').textContent.includes('36 horas'));
  console.log('tras 36 h:', await estado(), '|', await pausa());
  await pag.fill('#pHoras', '0');
  await pag.click('#pOtro');
  console.log('horas invalidas ->', await pag.textContent('#aviso'));
  await pag.click('button[data-h="24"]');
  await pag.waitForFunction(() => document.getElementById('aviso').textContent.includes('24 horas'));
  await pag.click('button[data-h="0"]');
  await pag.waitForFunction(() => document.getElementById('aviso').textContent.includes('quitada'));
  console.log('sin pausa:', await estado(), '|', await pausa());
  await pag.screenshot({ path: 'e2e_pausa_encendido.png', fullPage: true });
  await pag.click('#cEncender');
  await pag.waitForFunction(() => document.getElementById('estadoModo').textContent.includes('apagado'));
  console.log('apagado:', await estado(), '| boton:', await pag.textContent('#cEncender'), '| aviso:', await pag.textContent('#aviso'));
  console.log('pregunta de confirmacion:', dialogos[dialogos.length - 1]);
  await pag.screenshot({ path: 'e2e_pausa_apagado.png', fullPage: true });
  const nd = dialogos.length;
  await pag.click('#cEncender');
  await pag.waitForFunction(() => document.getElementById('estadoModo').textContent.includes('encendido'));
  console.log('encendido otra vez:', await estado(), '| boton:', await pag.textContent('#cEncender'), '| sin pregunta al encender:', dialogos.length === nd);
  await pag.click('#detCondiciones summary');
  await pag.click('#cGuardar');
  await pag.waitForFunction(() => document.getElementById('aviso').textContent.includes('guardadas'));
  console.log('guardar condiciones mantiene:', await estado());
  console.log('registro:', (await pag.textContent('#registro')).replace(/\s+/g, ' ').slice(0, 300));
  const ancho = await pag.evaluate(() => document.documentElement.scrollWidth);
  console.log('ancho de la pagina:', ancho, '(pantalla 390)', 'errores:', errores);
  await nav.close();
})().catch((e) => { console.log('FALLO', e.message); process.exit(1); });
